#!/usr/bin/env node
/**
 * Disposable Previewnet Wallet Generator (Zero External Dependencies).
 *
 * Generates a fresh Ed25519 Tezos wallet (tz1 / edpk / edsk) and a fresh secp256k1 EVM wallet
 * (EIP-55 0x address / pubkey / private key) and writes them with 0o600 permissions and
 * exclusive-create (`flag: 'wx'`) to `.env.previewnet` (or `--out <path>`).
 *
 * Security:
 * - Refuses to overwrite an existing file.
 * - NEVER prints private or secret keys to stdout/stderr.
 * - Strictly for ephemeral Tezos X Previewnet testing (NEVER use on mainnet with real funds).
 */

import { chmodSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import {
  generateEvmSecp256k1Wallet,
  generateTezosEd25519Wallet,
} from "./lib/wallets.mjs";

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(__dirname, "..");

const PREVIEWNET_DEFAULTS = {
  network: "previewnet",
  michelsonRpcUrl: "https://michelson.previewnet.tezosx.nomadic-labs.com",
  tezosChainId: "NetXY2oPPzkxUW1",
  evmRpcUrl: "https://evm.previewnet.tezosx.nomadic-labs.com",
  evmChainId: "128064",
  faucetUrl: "https://faucet.previewnet.tezosx.nomadic-labs.com",
};

function parseArgs(argv) {
  let outPath = resolve(ROOT, ".env.previewnet");
  for (let i = 0; i < argv.length; i++) {
    if (argv[i] === "--out" && argv[i + 1]) {
      outPath = resolve(process.cwd(), argv[++i]);
    }
  }
  return { outPath };
}

function buildEnvContent(tezos, evm) {
  return [
    "# Disposable Tezos X Previewnet wallets generated by NACBench.",
    "# NEVER commit this file and NEVER use these keys on mainnet.",
    `# Generated at: ${new Date().toISOString()}`,
    `NETWORK=${PREVIEWNET_DEFAULTS.network}`,
    "",
    "# Tezos Michelson Runtime (Ed25519)",
    `TEZOS_ADDRESS=${tezos.address}`,
    `TEZOS_PUBLIC_KEY=${tezos.publicKey}`,
    `TEZOS_SECRET_KEY=${tezos.secretKey}`,
    `TEZOS_PRIVATE_KEY=${tezos.secretKey}`,
    `MICHELSON_RPC_URL=${PREVIEWNET_DEFAULTS.michelsonRpcUrl}`,
    `TEZOS_RPC_URL=${PREVIEWNET_DEFAULTS.michelsonRpcUrl}`,
    `TEZOS_CHAIN_ID=${PREVIEWNET_DEFAULTS.tezosChainId}`,
    "",
    "# Etherlink EVM Runtime (secp256k1)",
    `EVM_ADDRESS=${evm.address}`,
    `EVM_PUBLIC_KEY=${evm.publicKey}`,
    `EVM_PRIVATE_KEY=${evm.privateKey}`,
    `EVM_RPC_URL=${PREVIEWNET_DEFAULTS.evmRpcUrl}`,
    `EVM_CHAIN_ID=${PREVIEWNET_DEFAULTS.evmChainId}`,
    "",
  ].join("\n");
}

function main() {
  const { outPath } = parseArgs(process.argv.slice(2));
  const tezos = generateTezosEd25519Wallet();
  const evm = generateEvmSecp256k1Wallet();
  const content = buildEnvContent(tezos, evm);

  try {
    writeFileSync(outPath, content, { encoding: "utf8", mode: 0o600, flag: "wx" });
    chmodSync(outPath, 0o600);
  } catch (err) {
    if (err?.code === "EEXIST") {
      console.error(
        `Refusing to overwrite existing wallet file: ${outPath}\n` +
          "Move, back up, or delete the existing file before generating new disposable wallets.",
      );
      process.exit(1);
    }
    throw err;
  }

  console.log(`Generated disposable Previewnet wallets -> ${outPath} (mode 0600)`);
  console.log("");
  console.log(`Tezos:        ${tezos.address}`);
  console.log(`Tezos pubkey: ${tezos.publicKey}`);
  console.log(`EVM:          ${evm.address}`);
  console.log("");
  console.log(`Faucet URL:   ${PREVIEWNET_DEFAULTS.faucetUrl}`);
  console.log("Fund BOTH the Tezos (tz1) and EVM (0x) addresses at the faucet, then run:");
  console.log("  npm run deploy:previewnet -- --live");
}

main();
